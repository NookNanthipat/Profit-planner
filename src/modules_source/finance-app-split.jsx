function genId() {
  return Date.now().toString(36) + Math.random().toString(36).slice(2, 6);
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

function formatDate(d) {
  if (!d) return "";
  try {
    return new Date(d + "T00:00:00").toLocaleDateString("th-TH", {
      day: "numeric",
      month: "short",
      year: "numeric",
    });
  } catch {
    return d;
  }
}

function daysUntil(dateStr) {
  if (!dateStr) return null;
  const diff = new Date(dateStr + "T00:00:00") - new Date(today() + "T00:00:00");
  return Math.round(diff / 86400000);
}

function money(n, currency = "THB") {
  const symbol = currency === "THB" ? "฿" : currency === "USD" ? "$" : currency;
  return `${symbol}${Number(n || 0).toLocaleString("th-TH", { maximumFractionDigits: 2 })}`;
}

