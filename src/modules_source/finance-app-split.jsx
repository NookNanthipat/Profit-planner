function getAllPeople(config) {
  return [{ id: "self", name: config.profile?.name || "ฉัน", color: "#6366f1", nickname: "Me" }, ...(config.people || [])];
}

function getSplitPaidAmount(payments, splitId, personId) {
  return payments
    .filter((p) => p.splitId === splitId && p.personId === personId)
    .reduce((sum, p) => sum + Number(p.amount || 0), 0);
}

function hydrateSplit(split, payments) {
  return {
    ...split,
    participants: (split.participants || []).map((participant) => {
      const paid = getSplitPaidAmount(payments, split.id, participant.personId);
      const actualAmount = Number(participant.actualAmount || 0);
      const delta = actualAmount - paid;
      return {
        ...participant,
        actualAmount,
        paidAmount: paid,
        remainingAmount: Math.max(0, delta),
        overpaidAmount: Math.max(0, -delta),
        isPaidFull: paid >= actualAmount - 0.01,
        isOverpaid: paid > actualAmount + 0.01,
      };
    }),
  };
}

